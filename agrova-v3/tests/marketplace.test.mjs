 invalid(()=>checkout(b1,l1,81,'too-many'));
 forbidden(()=>demoPay(b2,oid,'success'));
 assert.equal(demoPay(b1,oid,'uncertain').status,'uncertain');
 invalid(()=>demoPay(b1,oid,'success'));
