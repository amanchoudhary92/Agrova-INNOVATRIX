test('failed payment releases stock once; uncertain failure requires reconciliation',()=>{
 const fpo=fpoId();const b=create('buyer3@example.test','buyer');const l=add(admin,fpo,30);
 const id=checkout(b,l,12,'failed-1').data.order_id;
 assert.equal(demoPay(b,id,'failure').status,'failed');
 assert.equal(demoPay(b,id,'failure').idempotent,true);
 assert.equal(one('SELECT stock_kg FROM market_listings WHERE id=?',l).stock_kg,30);
 invalid(()=>demoPay(b,id,'success'));
 const next=checkout(b,l,6,'uncertain-2').data.order_id;
 assert.equal(demoPay(b,next,'uncertain').status,'uncertain');
 assert.equal(demoPay(b,next,'reconcile_failure').status,'failed');
 assert.equal(one('SELECT stock_kg FROM market_listings WHERE id=?',l).stock_kg,30);
 assert.equal(one('SELECT COUNT(*) n FROM market_invoices WHERE order_id IN (?,?)',id,next).n,0);
});

